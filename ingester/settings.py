"""Settings for the reduction, the capture command and the loader, read once from the environment.

`NODE_ID_HMAC_KEY` is a secret: it is held as a SecretStr, decoded once with
keys.parse_hmac_key, and never logged or printed. It is 32 random bytes
written as 64 hex characters, generated by Casey; a copy is kept off this
machine by Casey. The loader needs no key, so the field is optional here
and the commands that pseudonymise refuse to start without it.
"""

from functools import lru_cache
from pathlib import Path

from pydantic import SecretStr
from pydantic_settings import BaseSettings, SettingsConfigDict

from ingester.keys import parse_hmac_key

REPO_ROOT = Path(__file__).resolve().parents[1]


class MissingKeyError(RuntimeError):
    """NODE_ID_HMAC_KEY is not set."""


class IngesterSettings(BaseSettings):
    """Environment-backed settings; a `.env` at the repository root is read when present."""

    model_config = SettingsConfigDict(
        env_file=REPO_ROOT / ".env", env_file_encoding="utf-8", extra="ignore"
    )

    node_id_hmac_key: SecretStr | None = None
    snapshots_dir: Path = Path("C:/Users/Casey/mesh-terrain-data/snapshots")
    # The public broker's credentials are published by Meshtastic; the MeshSTL
    # broker's come from C:/Users/Casey/mesh-terrain-data/meshstl.env, never the repo.
    mqtt_user: str = "meshdev"
    mqtt_password: SecretStr = SecretStr("large4cats")

    def hmac_key(self) -> bytes:
        """The decoded key.

        Raises:
            MissingKeyError: if NODE_ID_HMAC_KEY is not set.
            ValueError: if it is not 32 bytes written as 64 hex characters.
        """
        if self.node_id_hmac_key is None or not self.node_id_hmac_key.get_secret_value():
            raise MissingKeyError("NODE_ID_HMAC_KEY is not set")
        return parse_hmac_key(self.node_id_hmac_key.get_secret_value().strip())


@lru_cache(maxsize=1)
def get_ingester_settings() -> IngesterSettings:
    """The process-wide settings, built on first call."""
    return IngesterSettings()
